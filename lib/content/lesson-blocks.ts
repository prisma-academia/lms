/**
 * The house vocabulary for designed lesson content.
 *
 * Generated lessons were a wall of paragraphs. The model had no way to say
 * "this is a warning" or "these are the three things that matter", so it said
 * everything in the same voice, and every lesson looked like every other one.
 *
 * These class names are that missing vocabulary. They are deliberately plain
 * CSS classes rather than components or custom elements, for three reasons:
 *
 *  1. `class` is already in the sanitizer's allowlist (`sanitize-html.ts`), so
 *     nothing here widens the security surface. A custom element would have to
 *     be allowed through, and then be allowed through for *authors* too.
 *  2. The same markup works in an HTML lesson written by hand, one pasted from
 *     elsewhere, and one generated by the AI builder. An author can use the
 *     vocabulary without knowing it came from the model.
 *  3. A class that is not styled degrades to an ordinary `<div>` — so a lesson
 *     rendered somewhere the stylesheet has not reached (an email digest, a
 *     plain-text extraction for the essay grader) is still readable prose.
 *
 * Styling lives beside `.lesson-prose` in `app/globals.css`. Keep this list and
 * that stylesheet in step: a class documented here but unstyled there produces a
 * lesson the model thinks it designed and the learner sees as flat text.
 */

export type LessonBlock = {
  /** The class name as written in lesson HTML. */
  className: string;
  /** What it is for, in the terms the prompt uses. */
  purpose: string;
  /** Minimal correct markup, quoted verbatim into the agent instructions. */
  example: string;
};

export const LESSON_BLOCKS: LessonBlock[] = [
  {
    className: "lesson-objectives",
    purpose: "What the learner will be able to do after this lesson. At most one, at the top.",
    example:
      '<aside class="lesson-objectives"><h3>By the end of this lesson</h3><ul><li>…</li></ul></aside>',
  },
  {
    className: "lesson-keypoints",
    purpose: "The two to five things that actually matter, pulled out of the prose.",
    example: '<aside class="lesson-keypoints"><h3>Key points</h3><ul><li>…</li></ul></aside>',
  },
  {
    className: "lesson-callout",
    purpose:
      "A note worth interrupting the reader for. Add a variant: lesson-callout-tip, lesson-callout-warning, or lesson-callout-note.",
    example: '<aside class="lesson-callout lesson-callout-warning"><p>…</p></aside>',
  },
  {
    className: "lesson-steps",
    purpose: "An ordered procedure the learner follows in sequence.",
    example: '<ol class="lesson-steps"><li><strong>Name the step.</strong> Then explain it.</li></ol>',
  },
  {
    className: "lesson-example",
    purpose: "A worked example: concrete inputs, and what comes out.",
    example: '<figure class="lesson-example"><figcaption>Example</figcaption><p>…</p></figure>',
  },
  {
    className: "lesson-term",
    purpose: "A term and its definition, where the term is the point.",
    example: '<dl class="lesson-term"><dt>Term</dt><dd>Definition.</dd></dl>',
  },
];

/**
 * The vocabulary as prompt text.
 *
 * Generated from the list rather than written out twice, so a block cannot be
 * added to the stylesheet and forgotten in the prompt — which would leave the
 * model unable to use a component that exists, the least visible kind of bug.
 */
export function lessonBlockGuide(): string {
  return LESSON_BLOCKS.map((b) => `- .${b.className} — ${b.purpose}\n  ${b.example}`).join("\n");
}
