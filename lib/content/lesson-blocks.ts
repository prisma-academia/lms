/** Classes that modify a block rather than name one. */
const VARIANT_CLASSES = ["lesson-callout-tip", "lesson-callout-warning", "lesson-callout-note"];

/**
 * Every class in the vocabulary: the blocks, the parts inside them and the
 * variants. Read out of the examples, so a part such as `.lesson-card` cannot
 * be used in an example and forgotten here.
 */
export function lessonBlockClasses(): Set<string> {
  const classes = new Set<string>(VARIANT_CLASSES);
  for (const block of LESSON_BLOCKS) {
    for (const markup of [block.example, block.starter ?? ""]) {
      for (const match of markup.matchAll(/class="([^"]+)"/g)) {
        for (const name of match[1].split(/\s+/)) if (name) classes.add(name);
      }
    }
  }
  return classes;
}

/**
 * The vocabulary as prompt text.
 *
 * Generated from the list rather than written out twice, so a block cannot be
 * added to the stylesheet and forgotten in the prompt — which would leave the
 * model unable to use a component that exists, the least visible kind of bug.
 */
export function lessonBlockGuide(): string {
  return LESSON_BLOCKS.map((b) => `- .${b.className} — ${b.purpose}\n  ${b.example}`).join("\n");
}
